function sanitize(s: string): string {
  return s
    .replace(/[\u2014\u2013]/g, "-")
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/\u2026/g, "...");
}

function fmtMoney(amount: number, currency: string, lang: PdfLang) {
  try {
    return new Intl.NumberFormat(lang === "da" ? "da-DK" : "en-GB", {
      style: "currency",
      currency,
    }).format(amount);
  } catch {
    return `${amount.toFixed(2)} ${currency}`;
  }
}

function fmtDate(iso: string | null | undefined, lang: PdfLang): string {
  if (!iso) return "-";
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso);
  if (!m) return iso;
  const [, y, mo, d] = m;
  return lang === "da" ? `${d}.${mo}.${y}` : `${d}/${mo}/${y}`;
}

// Neutral, print-safe palette with a single brand accent.
const INK = rgb(0x23 / 255, 0x24 / 255, 0x1f / 255);
const ACCENT = rgb(0x6b / 255, 0x93 / 255, 0xa8 / 255);
const MUTED = rgb(0.42, 0.45, 0.5);
const LINE = rgb(0.84, 0.84, 0.82);
const SOFT = rgb(0.96, 0.96, 0.95);

const MARGIN = 52;
const BODY = 9.5;
const HEAD = 11;

export async function generateReceiptPdf(data: ReceiptPdfData): Promise<Uint8Array> {
  const lang: PdfLang = data.lang === "en" ? "en" : "da";
  const t = L[lang];

  const doc = await PDFDocument.create();
  const page = doc.addPage([595.28, 841.89]);
  const { width, height } = page.getSize();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);

  const draw = (text: string, opts: Parameters<typeof page.drawText>[1]) =>
    page.drawText(sanitize(text), opts);
  const w = (text: string, size: number, f = font) => f.widthOfTextAtSize(sanitize(text), size);
  const drawRight = (
    text: string,
    x: number,
    y: number,
    size: number,
    f = font,
    color = INK,
  ) => draw(text, { x: x - w(text, size, f), y, size, font: f, color });

  const right = width - MARGIN;
  const currency = data.currency || "DKK";

  // ---------- Masthead ----------
  let y = height - MARGIN;
  draw("Kvitregn", { x: MARGIN, y: y - 12, size: 14, font: bold, color: INK });
  page.drawCircle({ x: MARGIN + w("Kvitregn", 14, bold) + 4, y: y - 8, size: 2, color: ACCENT });
  draw(t.tagline, { x: MARGIN, y: y - 26, size: 8, font, color: MUTED });

  const title = data.document_type === "invoice" ? t.invoice : t.receipt;
  drawRight(title, right, y - 14, 20, bold, INK);
  drawRight(
    data.doc_number != null
      ? `${t.docNo} ${String(data.doc_number).padStart(4, "0")}`
      : `${t.number} ${data.receipt_id.slice(0, 8).toUpperCase()}`,
    right,
    y - 30,
    BODY,
    font,
    MUTED,
  );

  y -= 46;
  page.drawLine({
    start: { x: MARGIN, y },
    end: { x: right, y },
    thickness: 1,
    color: ACCENT,
  });

  // ---------- Parties ----------
  y -= 26;
  const partyTop = y;
  const colRightX = MARGIN + (right - MARGIN) / 2 + 10;

  // Left: supplier ("Udstedt af")
  draw(t.billedBy, { x: MARGIN, y: partyTop, size: 8, font, color: MUTED });
  let ly = partyTop - 16;
  draw(data.company || "-", { x: MARGIN, y: ly, size: HEAD, font: bold, color: INK });
  ly -= 14;
  const supplierMeta: Array<[string, string]> = [];
  if (data.supplier_invoice_number?.trim())
    supplierMeta.push([t.invoiceNo, data.supplier_invoice_number.trim()]);
  if (data.supplier_cvr?.trim()) supplierMeta.push([t.cvr, data.supplier_cvr.trim()]);
  for (const [k, v] of supplierMeta) {
    draw(k, { x: MARGIN, y: ly, size: 8, font, color: MUTED });
    draw(v, { x: MARGIN + 62, y: ly, size: BODY, font, color: INK });
    ly -= 13;
  }

  // Right: own company ("Afsender")
  let ry = partyTop;
  if (data.sender) {
    const s = data.sender;
    draw(t.sender, { x: colRightX, y: ry, size: 8, font, color: MUTED });
    ry -= 16;
    const lines: Array<[string, boolean]> = [
      [s.company_name, true],
      [s.address ?? "", false],
      [[s.postal_code ?? "", s.city ?? ""].filter(Boolean).join(" "), false],
      [s.cvr ? `${t.cvr} ${s.cvr}` : "", false],
      [s.phone ? `${t.phone} ${s.phone}` : "", false],
      [s.email ?? "", false],
    ];
    for (const [line, isName] of lines) {
      if (!line.trim()) continue;
      draw(line, {
        x: colRightX,
        y: ry,
        size: isName ? HEAD : BODY,
        font: isName ? bold : font,
        color: isName ? INK : MUTED,
      });
      ry -= isName ? 15 : 12;
    }
  }

  // ---------- Meta row ----------
  y = Math.min(ly, ry) - 14;
  const meta: Array<[string, string]> = [
    [t.dateIssued, fmtDate(data.date, lang)],
    [t.category, data.category || t.uncategorized],
    [t.typeLabel, data.document_type === "invoice" ? t.invoice : t.receipt],
    [t.currencyLabel, currency],
  ];
  page.drawLine({ start: { x: MARGIN, y: y + 10 }, end: { x: right, y: y + 10 }, thickness: 0.5, color: LINE });
  let mx = MARGIN;
  const metaW = (right - MARGIN) / meta.length;
  for (const [k, v] of meta) {
    draw(k, { x: mx, y: y - 6, size: 8, font, color: MUTED });
    draw(v, { x: mx, y: y - 20, size: BODY, font: bold, color: INK });
    mx += metaW;
  }
  y -= 38;
  page.drawLine({ start: { x: MARGIN, y }, end: { x: right, y }, thickness: 0.5, color: LINE });

  // ---------- Items table ----------
  const items = data.items ?? [];
  y -= 26;

  const xDesc = MARGIN;
  const xQty = right - 250;
  const xUnit = right - 130;
  const xTotal = right;
  let subtotal = 0;

  if (items.length > 0) {
    draw(t.description, { x: xDesc, y, size: 8, font: bold, color: MUTED });
    drawRight(t.qty, xQty, y, 8, bold, MUTED);
    drawRight(t.unit, xUnit, y, 8, bold, MUTED);
    drawRight(t.total, xTotal, y, 8, bold, MUTED);
    y -= 8;
    page.drawLine({ start: { x: MARGIN, y }, end: { x: right, y }, thickness: 0.8, color: INK });
    y -= 16;

    const descMaxW = xQty - xDesc - 24;
    for (const it of items) {
      if (y < 250) break;
      let desc = sanitize(it.description || "");
      while (font.widthOfTextAtSize(desc, BODY) > descMaxW && desc.length > 3)
        desc = desc.slice(0, -2);
      draw(desc, { x: xDesc, y, size: BODY, font, color: INK });
      if (it.quantity != null) drawRight(String(it.quantity).replace(".", ","), xQty, y, BODY);
      if (it.unit_price != null)
        drawRight(fmtMoney(it.unit_price, currency, lang), xUnit, y, BODY);
      drawRight(fmtMoney(it.total, currency, lang), xTotal, y, BODY, font, INK);
      subtotal += it.total;
      y -= 9;
      page.drawLine({ start: { x: MARGIN, y }, end: { x: right, y }, thickness: 0.4, color: LINE });
      y -= 15;
    }
    y -= 6;
  }

  // ---------- Totals ----------
  // Uses the VAT stored on the document — never recomputed here.
  const gross = data.amount || 0;
  const hasVat = data.vat_amount != null && Number.isFinite(Number(data.vat_amount));
  const vat = hasVat ? Number(data.vat_amount) : 0;
  const exVat = gross - vat;
  const rateLabel =
    data.vat_rate != null && Number.isFinite(Number(data.vat_rate))
      ? ` ${String(Number(data.vat_rate)).replace(".", ",")}%`
      : "";
  const vatLabel =
    `${t.vat}${rateLabel}` + (data.vat_is_calculated === true ? ` (${t.vatCalculated})` : "");

  const boxW = 250;
  const boxX = right - boxW;
  const rowsH = 3 * 16 + 34;
  const boxY = y - rowsH;

  let ty = y - 14;
  if (hasVat) {
    drawRight(t.exVat, boxX + 150, ty, BODY, font, MUTED);
    drawRight(fmtMoney(exVat, currency, lang), right, ty, BODY, font, INK);
    ty -= 16;
    drawRight(vatLabel, boxX + 150, ty, BODY, font, MUTED);
    drawRight(fmtMoney(vat, currency, lang), right, ty, BODY, font, INK);
    ty -= 12;
  }
  page.drawLine({ start: { x: boxX, y: ty }, end: { x: right, y: ty }, thickness: 0.8, color: INK });
  ty -= 22;
  page.drawRectangle({ x: boxX, y: ty - 8, width: boxW, height: 28, color: SOFT });
  draw(hasVat ? t.grandTotal : t.total, { x: boxX + 8, y: ty, size: 9, font: bold, color: INK });
  drawRight(fmtMoney(gross, currency, lang), right - 8, ty - 1, 13, bold, INK);


  // Forfaldsdato highlighted, left of the totals
  if (data.due_date) {
    const dY = y - 30;
    page.drawRectangle({
      x: MARGIN,
      y: dY - 12,
      width: 190,
      height: 44,
      borderColor: ACCENT,
      borderWidth: 1,
    });
    draw(t.dueDate, { x: MARGIN + 10, y: dY + 16, size: 8, font, color: MUTED });
    draw(fmtDate(data.due_date, lang), {
      x: MARGIN + 10,
      y: dY,
      size: 13,
      font: bold,
      color: INK,
    });
  }

  y = Math.min(boxY, ty - 30);

  // ---------- Notes ----------
  const hasQr = !!data.verification_url;
  if (data.notes && y > 165) {
    draw(t.notes, { x: MARGIN, y, size: 8, font, color: MUTED });
    y -= 14;
    const words = sanitize(data.notes).split(/\s+/);
    let cur = "";
    const maxW = right - MARGIN - (hasQr ? 190 : 0);
    for (const word of words) {
      const test = cur ? `${cur} ${word}` : word;
      if (font.widthOfTextAtSize(test, BODY) > maxW) {
        draw(cur, { x: MARGIN, y, size: BODY, font, color: INK });
        y -= 13;
        cur = word;
        if (y < 135) break;
      } else cur = test;
    }
    if (cur && y > 125) draw(cur, { x: MARGIN, y, size: BODY, font, color: INK });
  }

  // ---------- QR verification ----------
  if (data.verification_url) {
    const qrSize = 68;
    const qrX = right - qrSize;
    const qrY = 96;
    try {
      const qr = QRCode.create(data.verification_url, { errorCorrectionLevel: "M" });
      const n = qr.modules.size;
      const bits = qr.modules.data;
      const cell = qrSize / n;
      page.drawRectangle({
        x: qrX - 10,
        y: qrY - 10,
        width: qrSize + 20,
        height: qrSize + 20,
        color: rgb(1, 1, 1),
      });
      for (let r = 0; r < n; r++) {
        for (let c = 0; c < n; c++) {
          if (!bits[r * n + c]) continue;
          page.drawRectangle({
            x: qrX + c * cell,
            y: qrY + (n - 1 - r) * cell,
            width: cell,
            height: cell,
            color: INK,
          });
        }
      }
      drawRight(t.verify, qrX - 12, qrY + qrSize - 10, 8, bold, INK);
      drawRight(t.verifyHint, qrX - 12, qrY + qrSize - 22, 7.5, font, MUTED);
    } catch (e) {
      console.warn("[receipt-pdf] qr failed", e);
    }
  }

  // ---------- Original document notice ----------
  draw(data.attachment ? t.originalFollows : t.noOriginal, {
    x: MARGIN,
    y: 92,
    size: 8,
    font: bold,
    color: data.attachment ? ACCENT : MUTED,
  });

  // ---------- Footer ----------
  const now = new Date();
  const stamp = (() => {
    try {
      const locale = lang === "da" ? "da-DK" : "en-GB";
      const d = new Intl.DateTimeFormat(locale, {
        day: "2-digit",
        month: "2-digit",
        year: "numeric",
        timeZone: "Europe/Copenhagen",
      }).format(now);
      const time = new Intl.DateTimeFormat(locale, {
        hour: "2-digit",
        minute: "2-digit",
        hour12: false,
        timeZone: "Europe/Copenhagen",
      }).format(now);
      return `${d} ${t.at} ${time}`;
    } catch {
      return now.toISOString().slice(0, 16).replace("T", " ");
    }
  })();

  page.drawLine({
    start: { x: MARGIN, y: 78 },
    end: { x: right, y: 78 },
    thickness: 0.5,
    color: LINE,
  });
  draw(`${t.documentId}: ${data.receipt_id}`, { x: MARGIN, y: 62, size: 7.5, font, color: MUTED });
  draw(`${t.generatedBy} ${stamp}`, {
    x: MARGIN,
    y: 50,
    size: 7.5,
    font,
    color: MUTED,
  });
  drawRight(t.footer, right, 50, 7.5, font, MUTED);

  // ---------- Original document pages ----------
  if (data.attachment) {
    try {
      await appendOriginal(doc, data.attachment, t.original, lang, data.doc_number ?? null);
    } catch (e) {
      console.error("[receipt-pdf] failed to append original", e);
    }
  }

  return await doc.save();
}

/**
 * Appends the original document after the summary page. Images become full
 * pages at their native pixel dimensions (1 px = 1 pt) so nothing is
 * downscaled and barcodes stay scannable; PDFs are merged page-for-page.
 */
async function appendOriginal(
  doc: PDFDocument,
  attachment: NonNullable<ReceiptPdfData["attachment"]>,
  label: string,
  lang: PdfLang,
  docNumber: number | null,
): Promise<void> {
  const font = await doc.embedFont(StandardFonts.HelveticaBold);
  const stampPage = (page: any) => {
    const { width, height } = page.getSize();
    const text = sanitize(
      docNumber != null
        ? `${label} - ${lang === "da" ? "Bilagsnr." : "Doc. no."} ${String(docNumber).padStart(4, "0")}`
        : label,
    );
    const size = Math.max(7, Math.min(11, width / 60));
    const tw = font.widthOfTextAtSize(text, size);
    page.drawRectangle({
      x: 0,
      y: height - size - 12,
      width: tw + 20,
      height: size + 12,
      color: rgb(1, 1, 1),
      opacity: 0.85,
    });
    page.drawText(text, {
      x: 10,
      y: height - size - 6,
      size,
      font,
      color: ACCENT,
    });
  };

  if (attachment.kind === "pdf") {
    const src = await PDFDocument.load(attachment.bytes, { ignoreEncryption: true });
    const pages = await doc.copyPages(src, src.getPageIndices());
    for (const p of pages) {
      doc.addPage(p);
      stampPage(p);
    }
    return;
  }

  const img =
    attachment.kind === "png"
      ? await doc.embedPng(attachment.bytes)
      : await doc.embedJpg(attachment.bytes);
  const page = doc.addPage([img.width, img.height]);
  page.drawImage(img, { x: 0, y: 0, width: img.width, height: img.height });
  stampPage(page);
}
