import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import QRCode from "qrcode";

export interface ReceiptPdfLineItem {
  description: string;
  quantity?: number | null;
  unit_price?: number | null;
  total: number;
}

export type PdfLang = "da" | "en";

export interface ReceiptPdfData {
  company: string;
  amount: number;
  currency: string;
  date: string;
  due_date?: string | null;
  document_type: "receipt" | "invoice";
  category?: string | null;
  notes?: string | null;
  /** Supplier's own invoice number from the source document. */
  supplier_invoice_number?: string | null;
  /** Supplier's CVR number from the source document. */
  supplier_cvr?: string | null;
  /** Stored VAT amount (kr). Null when the document has no VAT. */
  vat_amount?: number | null;
  /** Stored VAT rate in percent (25 = 25%). */
  vat_rate?: number | null;
  /** True when the VAT was calculated from the total instead of read from the document. */
  vat_is_calculated?: boolean;
  items?: ReceiptPdfLineItem[];

  receipt_id: string;
  /** Sequential per-user document number (bilagsnummer). */
  doc_number?: number | null;
  /** Kept for API compatibility; no longer rendered (no avatar on financial documents). */
  vendor_logo?: Uint8Array | null;
  /** Business profile of the user, rendered as an "Afsender" block. */
  sender?: {
    company_name: string;
    cvr?: string | null;
    address?: string | null;
    postal_code?: string | null;
    city?: string | null;
    phone?: string | null;
    email?: string | null;
  } | null;
  lang?: PdfLang;
  /**
   * The original document (processed scan when available, otherwise the raw
   * upload) appended after the summary page as "Originalbilag".
   */
  attachment?: { bytes: Uint8Array; kind: "pdf" | "jpg" | "png" } | null;
  /** Public verification URL encoded as a QR code on the summary page. */
  verification_url?: string | null;
}


