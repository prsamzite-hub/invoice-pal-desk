const STORAGE_KEY = "kvitregn.lang";

function detectInitial(): Lang {
  if (typeof window === "undefined") return "da";
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "da" || stored === "en") return stored;
  } catch {}
  try {
    const nav = window.navigator.language?.toLowerCase() ?? "";
    if (nav.startsWith("en")) return "en";
  } catch {}
  return "da";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("da");

  useEffect(() => {
    // Initial hydration: pick up localStorage / browser language
    const initial = detectInitial();
    setLangState(initial);
    try { document.documentElement.setAttribute("lang", initial === "en" ? "en" : "da"); } catch {}

    // If signed in, sync from profile (server truth wins)
    let cancelled = false;
    supabase.auth.getSession().then(({ data }) => {
      if (cancelled || !data.session) return;
      supabase
        .from("profiles")
        .select("locale")
        .eq("id", data.session.user.id)
        .maybeSingle()
        .then(({ data: row }) => {
          if (cancelled || !row?.locale) return;
          const l: Lang = row.locale.toLowerCase().startsWith("en") ? "en" : "da";
          setLangState(l);
          try {
            window.localStorage.setItem(STORAGE_KEY, l);
            document.documentElement.setAttribute("lang", l === "en" ? "en" : "da");
          } catch {}
        });
    });
    return () => { cancelled = true; };
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
      document.documentElement.setAttribute("lang", l === "en" ? "en" : "da");
    } catch {}
    // Best-effort persist to profile
    supabase.auth.getSession().then(({ data }) => {
      if (!data.session) return;
      const locale = l === "en" ? "en-DK" : "da-DK";
      supabase.from("profiles").update({ locale }).eq("id", data.session.user.id).then(() => {});
    });
  };

  const value = useMemo<Ctx>(() => {
    const locale = lang === "en" ? "en-DK" : "da-DK";
    const t = (k: Key) => (MERGED[lang][k as string] ?? MERGED.da[k as string] ?? (k as string)) as string;
    const tCategory = (raw?: string | null) => {
      if (!raw) return t("common.uncategorized");
      const key = `cat.${raw}` as Key;
      const v = MERGED[lang][key] ?? MERGED.da[key];
      return (v as string) ?? raw;
    };
    const formatDate = (input: string | Date | null | undefined, opts?: Intl.DateTimeFormatOptions) => {
      if (!input) return "—";
      const d = typeof input === "string" ? new Date(input) : input;
      if (isNaN(d.getTime())) return String(input);
      return new Intl.DateTimeFormat(locale, opts ?? { day: "2-digit", month: "short", year: "numeric" }).format(d);
    };
    const formatMoney = (v: number, currency = "DKK", opts?: Intl.NumberFormatOptions) => {
      try {
        return new Intl.NumberFormat(locale, { style: "currency", currency, ...(opts ?? {}) }).format(v);
      } catch {
        return `${v.toFixed(2)} ${currency}`;
      }
    };
    return { lang, setLang, t, tCategory, locale, formatDate, formatMoney };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [lang]);

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang(): Ctx {
  const ctx = useContext(LangContext);
  if (!ctx) {
    const locale = "da-DK";
    return {
      lang: "da",
      setLang: () => {},
      t: (k: string) => (MERGED.da[k] ?? k),
      tCategory: (raw?: string | null) => raw || "Ukategoriseret",
      locale,
      formatDate: (input) => (input ? new Date(input as any).toLocaleDateString(locale) : "—"),
      formatMoney: (v, currency = "DKK") => new Intl.NumberFormat(locale, { style: "currency", currency }).format(v),
    } as Ctx;
  }
  return ctx;
}
